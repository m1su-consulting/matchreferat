"""Generates branding/app-logo.svg: a girl with a ponytail kicking a football.

Limbs are tapered shapes between joints, so the silhouette reads as a person rather
than a stick figure. Adjust the joint positions below and re-run, then render with
Chrome (see FIREBASE.md for the headless command used for the PNG).
"""
import math
from pathlib import Path

GREEN = "#1F8A49"
FIGURE = "#FFFFFF"
BOOT = "#163A24"
HAIR_TIE = "#F4C542"


def limb(points, widths, fill=FIGURE, joints=True):
    """Tapered limb through `points` with a width per point, plus round joints."""
    left, right = [], []
    for i, (x, y) in enumerate(points):
        if i == 0:
            dx, dy = points[1][0] - x, points[1][1] - y
        elif i == len(points) - 1:
            dx, dy = x - points[i - 1][0], y - points[i - 1][1]
        else:
            dx, dy = points[i + 1][0] - points[i - 1][0], points[i + 1][1] - points[i - 1][1]
        length = math.hypot(dx, dy)
        nx, ny = -dy / length, dx / length
        half = widths[i] / 2
        left.append((x + nx * half, y + ny * half))
        right.append((x - nx * half, y - ny * half))
    outline = left + right[::-1]
    d = "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in outline) + " Z"
    caps = "".join(f'<circle cx="{x}" cy="{y}" r="{w / 2:.1f}" fill="{fill}"/>' for (x, y), w in zip(points, widths))
    return f'<path d="{d}" fill="{fill}"/>' + (caps if joints else "")


